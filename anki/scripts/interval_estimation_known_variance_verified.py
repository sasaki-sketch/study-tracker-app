# カード2: 信頼区間の計算式（母分散既知）
note2 = genanki.Note(
    model=model,
    fields=[
        '母平均の信頼区間の計算式（母分散既知）を示してください。',
        '''<b>基本公式</b><br>
母平均 μ の信頼係数100α%の信頼区間：<br><br>

\\[\\bar{X} - z_{\\alpha/2} \\cdot \\frac{\\sigma}{\\sqrt{n}} \\leq \\mu \\leq \\bar{X} + z_{\\alpha/2} \\cdot \\frac{\\sigma}{\\sqrt{n}}\\]<br><br>

または：<br>
\\[\\bar{X} \\pm z_{\\alpha/2} \\cdot \\frac{\\sigma}{\\sqrt{n}}\\]<br><br>

<b>記号の意味</b><br>
・X̄ = 標本平均<br>
・μ = 母平均（推定したい値）<br>
・σ = 母標準偏差（既知）<br>
・n = サンプルサイズ<br>
・z<sub>α/2</sub> = 標準正規分布の上側α/2点<br><br>

<b>95%信頼区間の場合</b><br>
α = 0.95 なので、上側2.5%点を使用：<br>
\\[\\bar{X} - 1.96 \\cdot \\frac{\\sigma}{\\sqrt{n}} \\leq \\mu \\leq \\bar{X} + 1.96 \\cdot \\frac{\\sigma}{\\sqrt{n}}\\]<br><br>

<b>標準誤差との関係</b><br>
σ/√n は標本平均の標準誤差（SE）なので：<br>
\\[\\text{信頼区間} = \\bar{X} \\pm z \\times \\text{SE}\\]<br><br>

<b>信頼区間の幅</b><br>
区間の幅 = \\[2 \\times z_{\\alpha/2} \\times \\frac{\\sigma}{\\sqrt{n}}\\]<br><br>

この幅は：<br>
・信頼係数が高いほど広くなる（zが大きくなる）<br>
・サンプルサイズが大きいほど狭くなる（√nが大きくなる）<br>
・母標準偏差が大きいほど広くなる<br><br>

<small>出典：統計WEB「母平均の信頼区間の求め方（母分散既知）」</small>'''
    ]
)
deck.add_note(note2)

# カード3: 信頼区間の計算手順
note3 = genanki.Note(
    model=model,
    fields=[
        '母平均の信頼区間を求める手順を説明してください（母分散既知）。',
        '''<b>4つのステップ</b><br><br>

<b>ステップ1：標本平均を求める</b><br>
標本データから平均値 X̄ を計算する。<br>
\\[\\bar{X} = \\frac{1}{n}\\sum_{i=1}^{n} X_i\\]<br><br>

<b>ステップ2：標本平均を標準化</b><br>
標準化式を確認：<br>
\\[Z = \\frac{\\bar{X} - \\mu}{\\sigma/\\sqrt{n}}\\]<br><br>

この Z は標準正規分布 N(0,1) に従う（中心極限定理による）。<br><br>

<b>ステップ3：標準正規分布から z値を確認</b><br>
信頼係数に応じた z値を標準正規分布表から求める：<br>
・90%信頼区間：z = 1.64（上側5%点）<br>
・95%信頼区間：z = 1.96（上側2.5%点）<br>
・99%信頼区間：z = 2.58（上側0.5%点）<br><br>

<b>ステップ4：信頼区間を求める</b><br>
公式に値を代入して計算：<br>
\\[\\bar{X} - z \\cdot \\frac{\\sigma}{\\sqrt{n}} \\leq \\mu \\leq \\bar{X} + z \\cdot \\frac{\\sigma}{\\sqrt{n}}\\]<br><br>

<b>具体例</b><br>
映画館スクリーン数のデータ：<br>
・標本平均：X̄ = 93.8<br>
・母分散：σ² = 5560（母標準偏差 σ ≈ 74.6）<br>
・サンプルサイズ：n = 10<br>
・信頼係数：95%（z = 1.96）<br><br>

計算：<br>
\\[93.8 - 1.96 \\times \\frac{74.6}{\\sqrt{10}} \\leq \\mu \\leq 93.8 + 1.96 \\times \\frac{74.6}{\\sqrt{10}}\\]<br><br>

\\[93.8 - 46.2 \\leq \\mu \\leq 93.8 + 46.2\\]<br><br>

<b>結果：47.6 ≤ μ ≤ 140.0</b><br><br>

<small>出典：統計WEB「母平均の信頼区間の求め方（母分散既知）」</small>'''
    ]
)
deck.add_note(note3)

# カード4: 95%信頼区間の正しい意味
note4 = genanki.Note(
    model=model,
    fields=[
        '95%信頼区間の正しい意味を説明してください。よくある誤解は？',
        '''<b>よくある誤解</b><br>
「母平均が95%の確率でこの信頼区間に含まれる」<br><br>

これは<b>不正確</b>です！<br><br>

<b>なぜ誤りなのか</b><br>
・母平均 μ は固定された定数であり、確率的に変動しない<br>
・算出された信頼区間は、母平均を「含む」か「含まない」かのどちらか<br>
・母平均に「確率」を割り当てることはできない（頻度主義統計学）<br><br>

<b>正しい解釈</b><br>
「母集団から標本を取ってきて、その標本平均から95%信頼区間を求める、という作業を100回やったときに、<b>95回はその区間の中に母平均が含まれる</b>」<br><br>

これは<b>確率ではなく頻度・割合</b>を意味する。<br><br>

<b>具体例で理解する</b><br>
日本人全体の平均身長が170cm（真の母平均）の場合：<br><br>

1. 100人の標本を抽出して95%信頼区間を計算する<br>
2. この作業を100回繰り返す<br>
3. 結果：約95個の区間が170cmを含み、約5個は含まない<br><br>

<b>重要なポイント</b><br>
・個々の信頼区間について「母平均が含まれる確率は95%」とは言えない<br>
・信頼区間は標本ごとに変わる（ランダムに変動する）<br>
・母平均は固定されている<br>
・95%は「手法の信頼性」を表す指標<br><br>

<b>正しい表現</b><br>
・「95%の信頼度で、母平均はこの区間に含まれる」<br>
・「この方法で区間を作ると、95%の割合で母平均を捉えられる」<br><br>

<b>誤った表現</b><br>
・「母平均が95%の確率でこの区間にある」❌<br>
・「候補Aの支持率が35%〜45%である確率は95%」❌<br><br>

<b>参考：ベイズ統計学</b><br>
ベイズ統計学の「信用区間」では、「母平均が95%の確率で推定区間に含まれる」という解釈が成立する。<br><br>

<small>出典：統計WEB「95%信頼区間のもつ意味」</small>'''
    ]
)
deck.add_note(note4)

